def pairs(deck, decl_num=None):
    out = []
    for lemma, gloss, table in deck:
        for (c, n), form in table.items():
            ans = {'c': c, 'n': n}
            if decl_num:
                ans = {'d': decl_num, 'c': c, 'n': n}
            out.append((form, ans, gloss))
    return out

