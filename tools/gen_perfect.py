# -*- coding: utf-8 -*-
"""Колоды по урокам 33–35: перфект и плюсквамперфект."""
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from koinegen import *

PVOICE_F = {'key': 'v', 'label': 'Залог', 'cols': 2,
            'options': [('act', 'актив'), ('mp', 'ср./пасс.')]}
PERSON_F = {'key': 'p', 'label': 'Лицо', 'cols': 3,
            'options': [('1', '1 л.'), ('2', '2 л.'), ('3', '3 л.')]}
VNUM_F   = {'key': 'n', 'label': 'Число', 'cols': 2,
            'options': [('sg', 'ед. ч.'), ('pl', 'мн. ч.')]}
SIX = [('1','sg'), ('2','sg'), ('3','sg'), ('1','pl'), ('2','pl'), ('3','pl')]
FMT = "function (a, label) { return label('v', a.v) + ', ' + label('p', a.p) + ' ' + label('n', a.n); }"

def verb(voice, gloss, *six):
    return [(f, {'v': voice, 'p': p, 'n': n}, gloss) for f, (p, n) in zip(six, SIX)]

# ===================== 1. Перфект (уроки 33–34) =====================

perf = []
PERF_ACT = [
 ('λύω → λέλυκα — освободил (и теперь свободен)',
  'λέλυκα','λέλυκας','λέλυκε(ν)','λελύκαμεν','λελύκατε','λελύκασι(ν)'),
 ('πιστεύω → πεπίστευκα — поверил (и верю)',
  'πεπίστευκα','πεπίστευκας','πεπίστευκε(ν)','πεπιστεύκαμεν','πεπιστεύκατε','πεπιστεύκασι(ν)'),
 ('ποιέω → πεποίηκα — сделал (слитный, ε → η)',
  'πεποίηκα','πεποίηκας','πεποίηκε(ν)','πεποιήκαμεν','πεποιήκατε','πεποιήκασι(ν)'),
 ('γράφω → γέγραφα — написал (сильный перфект, без -κ-)',
  'γέγραφα','γέγραφας','γέγραφε(ν)','γεγράφαμεν','γεγράφατε','γεγράφασι(ν)'),
 ('λέγω → εἴρηκα — сказал (супплетивный)',
  'εἴρηκα','εἴρηκας','εἴρηκε(ν)','εἰρήκαμεν','εἰρήκατε','εἰρήκασι(ν)'),
 ('ἔρχομαι → ἐλήλυθα — пришёл (и я здесь)',
  'ἐλήλυθα','ἐλήλυθας','ἐλήλυθε(ν)','ἐληλύθαμεν','ἐληλύθατε','ἐληλύθασι(ν)'),
 ('γινώσκω → ἔγνωκα — узнал (и знаю)',
  'ἔγνωκα','ἔγνωκας','ἔγνωκε(ν)','ἐγνώκαμεν','ἐγνώκατε','ἐγνώκασι(ν)'),
 ('ἀκούω → ἀκήκοα — услышал (удвоение с удлинением)',
  'ἀκήκοα','ἀκήκοας','ἀκήκοε(ν)','ἀκηκόαμεν','ἀκηκόατε','ἀκηκόασι(ν)'),
 ('ὁράω → ἑώρακα — увидел (и знаю)',
  'ἑώρακα','ἑώρακας','ἑώρακε(ν)','ἑωράκαμεν','ἑωράκατε','ἑωράκασι(ν)'),
]
PERF_MP = [
 ('λύω → λέλυμαι — освобождён / освободил себя',
  'λέλυμαι','λέλυσαι','λέλυται','λελύμεθα','λέλυσθε','λέλυνται'),
 ('πιστεύω → πεπίστευμαι — мне доверено',
  'πεπίστευμαι','πεπίστευσαι','πεπίστευται','πεπιστεύμεθα','πεπίστευσθε','πεπίστευνται'),
 ('ποιέω → πεποίημαι — сделан / сделал для себя',
  'πεποίημαι','πεποίησαι','πεποίηται','πεποιήμεθα','πεποίησθε','πεποίηνται'),
 ('γράφω → γέγραμμαι — написан (основа γεγραπ-)',
  'γέγραμμαι','γέγραψαι','γέγραπται','γεγράμμεθα','γέγραφθε','γέγρανται'),
]
for g, *six in PERF_ACT:
    perf += verb('act', g, *six)
for g, *six in PERF_MP:
    perf += verb('mp', g, *six)

emit('perfect', 'KOINE_DATA_PERFECT', 'Перфект', 'уроки 33–34',
     [PVOICE_F, PERSON_F, VNUM_F], merge(perf), fmt=FMT,
     comment='Залог виден по форме: -κα / -α — актив, -μαι, -σαι, -ται — средний/пассивный.\n'
             '   Средний и пассивный в перфекте, как и в praesens, не различаются — вариант один.')

