def verb(gloss, *six, **kw):
    """6 форм в порядке 1sg 2sg 3sg 1pl 2pl 3pl; extra — общие признаки (залог, время)."""
    extra = kw.get('extra', {})
    out = []
    for f, (p, n) in zip(six, SIX):
        ans = dict(extra); ans['p'] = p; ans['n'] = n
        out.append((f, ans, gloss))
    return out

