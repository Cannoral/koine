def three(m, f, n, only_sg=False):
    """три списка по 8 (или по 4, если only_sg) форм → {(род,падеж,число): форма}"""
    keys = [(c, 'sg') for c in CASES] + ([] if only_sg else [(c, 'pl') for c in CASES])
    out = {}
    for g, lst in (('m', m), ('f', f), ('n', n)):
        for (c, num), form in zip(keys, lst):
            out[(g, c, num)] = form
    return out

def ox(stem):   # ἀγαθός, -ή, -όν
    return three([stem+e for e in ['ός','οῦ','ῷ','όν','οί','ῶν','οῖς','ούς']],
                 [stem+e for e in ['ή','ῆς','ῇ','ήν','αί','ῶν','αῖς','άς']],
                 [stem+e for e in ['όν','οῦ','ῷ','όν','ά','ῶν','οῖς','ά']])

def oxr(stem):  # μικρός, -ά, -όν (после ρ)
    return three([stem+e for e in ['ός','οῦ','ῷ','όν','οί','ῶν','οῖς','ούς']],
                 [stem+e for e in ['ά','ᾶς','ᾷ','άν','αί','ῶν','αῖς','άς']],
                 [stem+e for e in ['όν','οῦ','ῷ','όν','ά','ῶν','οῖς','ά']])

