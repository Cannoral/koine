def verb(gloss, *six):
    return [(f, {'p': p, 'n': n}, gloss) for f, (p, n) in zip(six, SIX)]

def them(stem, gloss):   # нестяжённый: λύω, λύεις, λύει, λύομεν, λύετε, λύουσι(ν)
    return verb(gloss, *[stem + e for e in ['ω', 'εις', 'ει', 'ομεν', 'ετε', 'ουσι(ν)']])

def them_mp(stem, gloss):  # средний/пассивный тематический
    return verb(gloss, *[stem + e for e in ['ομαι', 'ῃ', 'εται', 'όμεθα', 'εσθε', 'ονται']])

