def part(voice, gloss, m, f, n):
    keys = [(c, 'sg') for c in CASES] + [(c, 'pl') for c in CASES]
    out = []
    for g, lst in (('m', m), ('f', f), ('n', n)):
        for (c, num), form in zip(keys, lst):
            out.append((form, {'v': voice, 'c': c, 'n': num, 'g': g}, gloss))
    return out

