def rows(slots, gloss, forms, **extra):
    """forms по порядку slots; extra — общие признаки. Залог 'mp' даёт два ответа."""
    out = []
    for f, (p, n) in zip(forms, slots):
        voices = ['mid', 'pass'] if extra.get('v') == 'mp' else [extra.get('v')]
        for v in voices:
            ans = dict(extra)
            if v is not None:
                ans['v'] = v
            ans['p'], ans['n'] = p, n
            out.append((f, ans, gloss))
    return out

